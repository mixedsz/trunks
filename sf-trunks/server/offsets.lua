-- Vehicle trunk offsets table
-- Each entry is indexed by the vehicle model hash (integer returned by GetEntityModel)
-- o = position offset (x, y, z) relative to vehicle bone 0
-- r = rotation offset (x, y, z) in degrees
--
-- Use the in-game offset editor (Config.DevMode = true, then /trunk_create) to generate
-- and save new offsets for additional vehicles. Values are tuned for a crouching-in-trunk pose.

Offsets = Offsets or {}

-- Helper to register an offset by model name (converted to hash server-side)
local function AddOffset(modelName, ox, oy, oz, rx, ry, rz)
    local hash = GetHashKey(modelName)
    Offsets[hash] = {
        o = { x = ox, y = oy, z = oz },
        r = { x = rx, y = ry, z = rz },
    }
end

